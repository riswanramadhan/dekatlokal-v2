export function sampleContent(category: SiteCategory): SiteContent {
  return structuredClone(SAMPLE_CONTENT[category]);
}

const ALL_SAMPLES = Object.values(SAMPLE_CONTENT);
const SAMPLE_PRODUCTS = new Set(ALL_SAMPLES.flatMap((item) => item.products.map((product) => product.name)));
const SAMPLE_SERVICES = new Set(ALL_SAMPLES.flatMap((item) => item.services.map((service) => service.title)));
const SAMPLE_QUOTES = new Set(ALL_SAMPLES.flatMap((item) => item.testimonials.map((t) => t.quote)));
const SAMPLE_ABOUT = new Set(ALL_SAMPLES.map((item) => item.about));

/** Isi yang masih sama persis dengan contoh (diingatkan sebelum terbit supaya pelanggan tidak salah info). */
export function sampleLeftovers(content: SiteContent): string[] {
  return [
    ...content.products.filter((product) => SAMPLE_PRODUCTS.has(product.name)).map((product) => product.name),
    ...content.services.filter((service) => SAMPLE_SERVICES.has(service.title)).map((service) => service.title),
    ...content.testimonials.filter((t) => SAMPLE_QUOTES.has(t.quote)).map((t) => `Testimoni ${t.name}`),
    ...(SAMPLE_ABOUT.has(content.about) ? ["Cerita usaha"] : []),
  ];
}
